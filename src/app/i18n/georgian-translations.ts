const GEORGIAN_RULES: GeorgianRule[] = [
  {
    pattern: /^(\d+)\s+Beds?$/i,
    translate: (match) => `${match[1]} საძინებელი`,
  },
  {
    pattern: /^(\d+)\s+Baths?$/i,
    translate: (match) => `${match[1]} სააბაზანო`,
  },
  {
    pattern: /^(\d+)\s+Bedrooms?$/i,
    translate: (match) => `${match[1]} საძინებელი`,
  },
  {
    pattern: /^(\d+)\s+Rooms?$/i,
    translate: (match) => `${match[1]} ოთახი`,
  },
  {
    pattern: /^(\d+)\s+min walk$/i,
    translate: (match) => `${match[1]} წუთის სავალზე`,
  },
  {
    pattern: /^(\d+)\s+days? ago$/i,
    translate: (match) => `${match[1]} დღის წინ`,
  },
  {
    pattern: /^(\d+)(?:st|nd|rd|th) floor$/i,
    translate: (match) => `მე-${match[1]} სართული`,
  },
  {
    pattern: /^Active Listings \((\d+)\)$/i,
    translate: (match) => `აქტიური განცხადებები (${match[1]})`,
  },
  {
    pattern: /^(\d+) properties? saved$/i,
    translate: (match) => `შენახულია ${match[1]} ობიექტი`,
  },
  {
    pattern: /^Contact (.+)$/i,
    translate: (match) => `${match[1]}-თან დაკავშირება`,
  },
  {
    pattern: /^Up to (.+)$/i,
    translate: (match) => `${match[1]}-მდე`,
  },
  {
    pattern: /^Search street in (.+)…$/i,
    translate: (match) => `${match[1]} — ქუჩის ძიება…`,
  },
  {
    pattern: /^Search (Users|Apartments|Blogs)$/i,
    translate: (match) => {
      const subjects: Record<string, string> = {
        Users: 'მომხმარებლების',
        Apartments: 'ბინების',
        Blogs: 'ბლოგების',
      };
      return `${subjects[match[1]]} ძიება`;
    },
  },
  {
    pattern: /^Remove (.+)$/i,
    translate: (match) => `${match[1]} — წაშლა`,
  },
];

export function georgianTranslation(value: string): string | undefined {
  const exact = GEORGIAN_TRANSLATIONS.get(value);
  if (exact) return exact;

  for (const rule of GEORGIAN_RULES) {
    const match = value.match(rule.pattern);
    if (match) return rule.translate(match);
  }

  return undefined;
}
