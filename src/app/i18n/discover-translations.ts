export function discoverTranslation(value: string, language: 'ka' | 'ru'): string | undefined {
  const column = language === 'ka' ? 1 : 2;
  const exact = COPY.find(row => row[0].toLowerCase() === value.toLowerCase());
  if (exact) return exact[column];
  const apartment = value.match(/^A new (?:(\d+)-bedroom )?apartment in (.+) matches your preferences\.$/);
  if (apartment) return language === 'ka'
    ? `ახალი ${apartment[1] ? apartment[1] + '-საძინებლიანი ' : ''}ბინა (${apartment[2]}) თქვენს სურვილებს ემთხვევა.`
    : `Новая квартира${apartment[1] ? ' с ' + apartment[1] + ' спальнями' : ''} в районе ${apartment[2]} соответствует вашим предпочтениям.`;
  return undefined;
}
