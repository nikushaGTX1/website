const RUSSIAN_RULES: RussianRule[] = [
  {
    pattern: /^Step (\d+) of (\d+)$/i,
    translate: (match) => `Шаг ${match[1]} из ${match[2]}`,
  },
  {
    pattern: /^Show all (\d+) photos$/i,
    translate: (match) => `Показать все фото (${match[1]})`,
  },
  {
    pattern: /^(\d+) min walk$/i,
    translate: (match) => `${match[1]} мин пешком`,
  },
  {
    pattern: /^(\d+) Beds?$/i,
    translate: (match) => `${match[1]} спал.`,
  },
  {
    pattern: /^(\d+) Baths?$/i,
    translate: (match) => `${match[1]} ванн.`,
  },
  {
    pattern: /^Thank you, (.+)\.$/i,
    translate: (match) => `Спасибо, ${match[1]}.`,
  },
  {
    pattern: /^Up to (.+)$/i,
    translate: (match) => `До ${match[1]}`,
  },
  {
    pattern: /^Remove (.+)$/i,
    translate: (match) => `Удалить ${match[1]}`,
  },
  {
    pattern: /^(\d+)\s+Rooms?$/i,
    translate: (match) => `${match[1]} комн.`,
  },
  {
    pattern: /^(\d+)\s+Bedrooms?$/i,
    translate: (match) => `${match[1]} спальни`,
  },
  {
    pattern: /^(\d+)%\s*complete$/i,
    translate: (match) => `Заполнено на ${match[1]}%`,
  },
  {
    pattern: /^(\d+)\s*\/\s*(\d+)\s+uploaded$/i,
    translate: (match) => `Загружено ${match[1]} из ${match[2]}`,
  },
  {
    pattern: /^Contact (.+)$/i,
    translate: (match) => `Связаться с ${match[1]}`,
  },
  {
    pattern: /^The original owner of this listing is (.+)\.$/i,
    translate: (match) => `Первоначальный владелец этого объявления — ${match[1]}.`,
  },
  {
    pattern: /^Homes (for sale|for rent) in (.+)$/i,
    translate: (match) =>
      `Дома ${match[1].toLowerCase() === 'for sale' ? 'на продажу' : 'в аренду'} в ${match[2]}`,
  },
  {
    pattern: /^([\d,.\s]+) verified homes in this map area$/i,
    translate: (match) => `${match[1].trim()} проверенных объектов в этой области карты`,
  },
];

export function russianTranslation(value: string): string | undefined {
  const exact = RUSSIAN_TRANSLATIONS.get(value);
  if (exact) return exact;

  const decorated = value.match(/^(\s*[^A-Za-z]*?)([A-Za-z].*)$/);
  if (decorated?.[1]) {
    const translated = RUSSIAN_TRANSLATIONS.get(decorated[2]);
    if (translated) return `${decorated[1]}${translated}`;
  }

  for (const rule of RUSSIAN_RULES) {
    const match = value.match(rule.pattern);
    if (match) return rule.translate(match);
  }

  return undefined;
}
